export interface BuildLevelOpts {
  id: number;
  name: string;
  hint: string;
  /** 多行字符串；行数 = height，列数取最长行长（自动补 '.'） */
  map: string;
  /** 用时 <= 此值 且拿到全部宝石 → 3 星（秒） */
  twoStarTime: number;
  triggers?: TriggerDef[];
  movingPlatforms?: MovingPlatformDef[];
  gates?: GateDef[];
}

export function buildLevel(o: BuildLevelOpts): LevelDef {
  const rawLines = o.map.replace(/\r\n/g, '\n').split('\n');
  while (rawLines.length > 0 && rawLines[rawLines.length - 1].trim() === '') rawLines.pop();
  while (rawLines.length > 0 && rawLines[0].trim() === '') rawLines.shift();
  const width = rawLines.reduce((m, l) => Math.max(m, l.length), 0);
  const height = rawLines.length;
  const map: string[] = rawLines.map((l) => l.padEnd(width, '.'));

  const gems: GemDef[] = [];
  const boxes: { col: number; row: number }[] = [];
  let fireSpawn: { x: number; y: number } | null = null;
  let waterSpawn: { x: number; y: number } | null = null;
  let fireDoor: { col: number; row: number } | null = null;
  let waterDoor: { col: number; row: number } | null = null;

  for (let y = 0; y < height; y++) {
    const row = map[y].split('');
    for (let x = 0; x < width; x++) {
      switch (row[x]) {
        case 'F': fireSpawn = { x, y }; row[x] = '.'; break;
        case 'W': waterSpawn = { x, y }; row[x] = '.'; break;
        case 'D': fireDoor = { col: x, row: y }; row[x] = '.'; break;
        case 'd': waterDoor = { col: x, row: y }; row[x] = '.'; break;
        case 'r': gems.push({ col: x, row: y, kind: 'fire' }); row[x] = '.'; break;
        case 'b': gems.push({ col: x, row: y, kind: 'water' }); row[x] = '.'; break;
        case 'o': boxes.push({ col: x, row: y }); row[x] = '.'; break;
      }
    }
    map[y] = row.join('');
  }

  if (!fireSpawn) throw new Error(`level ${o.id} 缺少火男出生点 F`);
  if (!waterSpawn) throw new Error(`level ${o.id} 缺少水女出生点 W`);
  if (!fireDoor) throw new Error(`level ${o.id} 缺少火门 D`);
  if (!waterDoor) throw new Error(`level ${o.id} 缺少水门 d`);

  const def: LevelDef = {
    id: o.id,
    name: o.name,
    hint: o.hint,
    width,
    height,
    map,
    spawns: { fire: fireSpawn, water: waterSpawn },
    doors: {
      fire: { col: fireDoor.col, row: fireDoor.row, kind: 'fire' },
      water: { col: waterDoor.col, row: waterDoor.row, kind: 'water' },
    },
    gems,
    boxes,
    triggers: o.triggers ?? [],
    movingPlatforms: o.movingPlatforms ?? [],
    gates: o.gates ?? [],
    twoStarTime: o.twoStarTime,
  };

  const errs = validateLevel(def);
  if (errs.length) throw new Error(`关卡 ${o.id} "${o.name}" 数据有误：\n  ${errs.join('\n  ')}`);
  return def;
}

